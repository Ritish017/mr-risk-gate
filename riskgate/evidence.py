"""Compliance evidence bundle (govern stage).

Collects the facts an auditor asks for after a change ships — who/what/when,
the risk verdict and why, which checks ran and their outcome — from
predefined CI variables and the artifacts earlier jobs produced. Missing
inputs are reported as missing, never invented.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from xml.etree import ElementTree

CI_FIELDS = [
    ("Project", "CI_PROJECT_PATH"),
    ("Pipeline", "CI_PIPELINE_URL"),
    ("Commit", "CI_COMMIT_SHA"),
    ("Branch / tag", "CI_COMMIT_REF_NAME"),
    ("Merge request", "CI_MERGE_REQUEST_IID"),
    ("Triggered by", "GITLAB_USER_LOGIN"),
    ("Pipeline source", "CI_PIPELINE_SOURCE"),
]


def junit_summary(path: Path) -> dict | None:
    if not path.exists():
        return None
    root = ElementTree.parse(path).getroot()
    suites = [root] if root.tag == "testsuite" else list(root.iter("testsuite"))
    tot = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0}
    for s in suites:
        for k in tot:
            tot[k] += int(s.get(k, 0) or 0)
    return tot


def security_summary(paths: list[Path]) -> dict:
    out = {}
    for p in paths:
        if p.exists():
            data = json.loads(p.read_text(encoding="utf-8"))
            vulns = data.get("vulnerabilities", [])
            by_sev: dict[str, int] = {}
            for v in vulns:
                sev = v.get("severity", "Unknown")
                by_sev[sev] = by_sev.get(sev, 0) + 1
            out[p.name] = by_sev
        else:
            out[p.name] = None
    return out


def sha256(path: Path) -> str | None:
    if not path.exists():
        return None
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_evidence(risk_json: Path, junit_xml: Path, security_reports: list[Path],
                   env: dict | None = None, mutation_json: Path | None = None) -> str:
    env = env if env is not None else dict(os.environ)
    lines = ["# Change evidence bundle", ""]
    lines += ["| Field | Value |", "|---|---|"]
    for label, var in CI_FIELDS:
        lines.append(f"| {label} | {env.get(var, '_not available_')} |")
    lines.append("")

    lines.append("## Risk verdict")
    if risk_json.exists():
        r = json.loads(risk_json.read_text(encoding="utf-8"))
        lines.append(f"**{r['level']}** ({r['score']}/100) — sha256 `{sha256(risk_json)}`")
        for f in r.get("findings", [])[:10]:
            lines.append(f"- {f['points']} pts `{f['rule']}`: {f['reason']}")
    else:
        lines.append("_risk report missing (not an MR pipeline, or risk job did not run)_")
    lines.append("")

    lines.append("## Tests")
    j = junit_summary(junit_xml)
    lines.append(
        f"{j['tests']} tests, {j['failures']} failures, {j['errors']} errors, {j['skipped']} skipped"
        if j else "_JUnit report missing_"
    )
    lines.append("")

    if mutation_json is not None:
        lines.append("## Test proof (mutation)")
        if mutation_json.exists():
            m = json.loads(mutation_json.read_text(encoding="utf-8"))
            if m.get("total"):
                lines.append(f"**{m['verdict']}**: {m['killed']}/{m['total']} bugs planted on changed lines were caught "
                             f"(policy ≥ {m.get('min_kill_ratio', 0.8) * 100:.0f}%) — sha256 `{sha256(mutation_json)}`")
                for mu in m.get("mutants", []):
                    if mu.get("status") == "survived":
                        lines.append(f"- survived: `{mu['path']}:{mu['line']}` `{mu['original']}` → `{mu['mutated']}`")
            else:
                lines.append(f"**{m.get('verdict')}** (no mutants scored)")
        else:
            lines.append("_mutation report missing_")
        lines.append("")

    lines.append("## Security scans")
    for name, sev in security_summary(security_reports).items():
        if sev is None:
            lines.append(f"- `{name}`: _report missing_")
        elif not sev:
            lines.append(f"- `{name}`: no findings")
        else:
            lines.append(f"- `{name}`: " + ", ".join(f"{k}: {v}" for k, v in sorted(sev.items())))
    lines.append("")
    lines.append("_Generated by `riskgate evidence`; every value above comes from CI variables or job artifacts._")
    return "\n".join(lines) + "\n"
